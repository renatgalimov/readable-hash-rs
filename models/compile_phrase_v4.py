#!/usr/bin/env python3
"""Compile only v4's ending rows, keeping every v3 table frozen."""
import argparse
import json
from collections import Counter
from pathlib import Path

from compile_phrase import CONTEXTS, emitted, prefix_free, valid
from reversible_tables import choose_prefix_free, load_training_counts

ROOT = Path(__file__).resolve().parent


def compile_rows():
    model = json.loads((ROOT / 'phrase_v3_model.json').read_text())
    tokens = model['tokens']
    counts = load_training_counts(ROOT / 'training-data/english-lowercase.txt', ROOT / 'training-data/english-lowercase-model.json')
    pool = {emitted(tokens[index]): index for index in range(256, 512)
            if tokens[index].endswith('$') and valid(emitted(tokens[index]))}
    global_counts = sum(counts['end'].values(), Counter())
    rows, omissions, cache = [], {}, {}
    for context in CONTEXTS:
        local = counts['end'].get(context, Counter())
        key = tuple(sorted(local.items()))
        if key not in cache:
            candidates = {text: (local.get(index, 0), global_counts[index] if not local.get(index, 0) else 0)
                          for text, index in pool.items()}
            cache[key] = [pool[text] for text in choose_prefix_free(candidates, 16)]
        row = cache[key]
        assert len(row) == 16 and all(256 <= index < 512 for index in row)
        assert prefix_free([emitted(tokens[index]) for index in row])
        rows.append(row)
        missing = [tokens[index] for index in sorted(local) if index not in set(row)]
        if missing:
            omissions[str(context)] = missing
    return rows, omissions


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    rows, omissions = compile_rows()
    outputs = {
        ROOT / 'phrase_v4_end16.json': json.dumps({'contexts': CONTEXTS, 'end16': rows, 'omitted_local_tokens_by_context_id': omissions}, sort_keys=True, separators=(',', ':')) + '\n',
        ROOT.parent / 'src/phrase_v4_data.rs': '// Generated by models/compile_phrase_v4.py; do not edit.\n#![allow(clippy::unreadable_literal)]\n#[rustfmt::skip]\npub static END16: [[u16; 16]; 768] = ' + json.dumps(rows) + ';\n',
    }
    for path, output in outputs.items():
        if args.check:
            if path.read_text() != output:
                raise SystemExit(f'generated file differs: {path}')
        else:
            path.write_text(output)
    print('v4: 768 prefix-free E16 rows verified')


if __name__ == '__main__':
    main()
