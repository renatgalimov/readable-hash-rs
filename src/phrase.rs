//! Reversible, pronounceable phrases for 64-bit values: "the bits are in the spaces".
//!
//! [`encode_u64`] turns any `u64` into a short phrase such as `mung kiroot niun yeekwa`, and
//! [`decode_u64`] turns the phrase back into the same number. Both are total and exact: every value
//! has one phrase, and every phrase it produces decodes to its value. This is an encoding, not
//! encryption or hashing.
//!
//! A phrase is 10 tokens in 3 or 4 words of 2 to 4 tokens each: a beginning, 0 to 2 middles and an
//! ending. There are exactly 16 such layouts, so the layout stores the low 4 bits. The tokens store
//! the other 60: a beginning takes 7 bits (128 choices), a middle 6 (64) and an ending 5 (32). A
//! beginning and an ending together take 12 bits, as much as two middles, so every layout is exactly
//! 64 bits: 4 + 3×7 + 4×6 + 3×5 with 3 words, and 4 + 4×7 + 2×6 + 4×5 with 4 words.
//!
//! Each middle and ending table depends on the previous token. In every context the middles and
//! endings together are prefix-free, and no token is shorter than 2 letters, so the decoder finds
//! every token boundary, and with it the layout, from the letters alone. Every word has a vowel
//! (a, e, i, o, u or y): a beginning without one is always followed by a token with one. No letter
//! appears three times in a row, and no three vowels (a, e, i, o, u) follow each other.
//!
//! The tables are generated by `models/compile_phrase.py` (format id `phrase-v7`) from the
//! words of 153 languages (mostly ones that are easy to pronounce, plus English, German, Old English,
//! Old Norse, Old High German and constructed languages from Esperanto to Tolkien's Quenya and Klingon), so phrases sound
//! like no language in particular and rarely form real words. No word a phrase can contain includes an offensive word
//! from the lists of any language (terms of 5+ letters anywhere in a word, 4-letter terms at its
//! start); the compiler checks every word the tables can produce. Changing the tables changes
//! every phrase, so treat them as a stable format.
//!
//! ```
//! let phrase = readable_hash::phrase::encode_u64(0x243f6a8885a308d3);
//! assert_eq!(phrase, "mung kiroot niun yeekwa");
//! assert_eq!(readable_hash::phrase::decode_u64(&phrase), Some(0x243f6a8885a308d3));
//! ```
use crate::phrase_data as data;
use std::sync::OnceLock;

/// Word lengths in tokens (0 = no word), in the order of their 4-bit index: sorted lexicographically.
const LAYOUTS: [[u8; 4]; 16] = [
    [2, 2, 2, 4],
    [2, 2, 3, 3],
    [2, 2, 4, 2],
    [2, 3, 2, 3],
    [2, 3, 3, 2],
    [2, 4, 2, 2],
    [2, 4, 4, 0],
    [3, 2, 2, 3],
    [3, 2, 3, 2],
    [3, 3, 2, 2],
    [3, 3, 4, 0],
    [3, 4, 3, 0],
    [4, 2, 2, 2],
    [4, 2, 4, 0],
    [4, 3, 3, 0],
    [4, 4, 2, 0],
];
const MAX_MIDDLES: usize = 2;
/// Bits per choice: 16 layouts, 128 beginnings, 64 middles, 32 endings (`validate` checks the tables).
const LAYOUT_BITS: u32 = 4;
const BEGIN_BITS: u32 = 7;
const MIDDLE_BITS: u32 = 6;
const END_BITS: u32 = 5;

fn text(token: u16) -> &'static str {
    data::TOKENS[token as usize]
        .trim_start_matches('^')
        .trim_end_matches('$')
}

/// The row after a middle. Rows 0-127 follow the beginnings (by their index in `BEGIN`), rows
/// 128-639 follow the middles 512-1023.
fn middle_row(token: u16) -> usize {
    data::BEGIN.len() + token as usize - 512
}

fn word_count(layout: &[u8; 4]) -> usize {
    layout.iter().filter(|&&length| length != 0).count()
}

fn has_vowel(spelling: &str) -> bool {
    spelling.bytes().any(|byte| b"aeiouy".contains(&byte))
}

/// No letter three times in a row, and no three vowels in a row, across the join of the previous
/// token and this one.
fn triple_free(previous: &str, piece: &str) -> bool {
    let tail = &previous.as_bytes()[previous.len().saturating_sub(2)..];
    let joined: Vec<u8> = tail.iter().copied().chain(piece.bytes()).collect();
    !joined
        .windows(3)
        .any(|w| (w[0] == w[1] && w[1] == w[2]) || w.iter().all(|byte| b"aeiou".contains(byte)))
}

fn validate() {
    static VALID: OnceLock<()> = OnceLock::new();
    VALID.get_or_init(|| {
        fn prefix_free(texts: &[&str]) -> bool {
            texts.iter().enumerate().all(|(index, first)| {
                texts[index + 1..]
                    .iter()
                    .all(|second| !first.starts_with(second) && !second.starts_with(first))
            })
        }
        let plain = |token: &u16| {
            let spelling = text(*token);
            spelling.len() >= 2 && spelling.bytes().all(|byte| byte.is_ascii_lowercase())
        };
        assert_eq!(LAYOUTS.len(), 1 << LAYOUT_BITS);
        assert_eq!(data::BEGIN.len(), 1 << BEGIN_BITS);
        assert_eq!(data::MIDDLE[0].len(), 1 << MIDDLE_BITS);
        assert_eq!(data::END32[0].len(), 1 << END_BITS);
        assert!(
            data::BEGIN
                .iter()
                .all(|&token| token < 256 && plain(&token))
        );
        assert!(prefix_free(&data::BEGIN.map(text)));
        assert!(
            data::BEGIN
                .iter()
                .all(|&token| triple_free("", text(token)))
        );
        assert_eq!(data::MIDDLE.len(), data::BEGIN.len() + 512);
        for row in 0..data::MIDDLE.len() {
            let (middles, endings) = (&data::MIDDLE[row], &data::END32[row]);
            assert!(middles.iter().all(|&token| (512..1024).contains(&token)));
            assert!(endings.iter().all(|&token| (256..512).contains(&token)));
            assert!(middles.iter().chain(endings).all(plain));
            let union: Vec<&str> = middles
                .iter()
                .chain(endings)
                .map(|&token| text(token))
                .collect();
            assert!(
                prefix_free(&union),
                "context {row}: middles and endings overlap"
            );
            let beginning = row < data::BEGIN.len();
            let previous = text(if beginning {
                data::BEGIN[row]
            } else {
                (row - data::BEGIN.len() + 512) as u16
            });
            // Every word needs a vowel: after a beginning without one, every middle and ending has one.
            if beginning && !has_vowel(previous) {
                assert!(union.iter().all(|piece| has_vowel(piece)), "context {row}");
            }
            // No letter, and no vowel, three times in a row: tokens have 2+ letters, so such a run
            // spans at most one join.
            assert!(
                union.iter().all(|piece| triple_free(previous, piece)),
                "context {row}: three in a row"
            );
        }
    });
}

/// The low `bits` of `value` as a table index; shifts them out.
fn take(value: &mut u64, bits: u32) -> usize {
    let digit = *value & ((1 << bits) - 1);
    *value >>= bits;
    digit as usize
}

/// Encode least-significant bits first: the layout, then each word's tokens left to right.
pub fn encode_u64(mut value: u64) -> String {
    validate();
    let layout = &LAYOUTS[take(&mut value, LAYOUT_BITS)];
    let mut phrase = String::new();
    for (position, &length) in layout[..word_count(layout)].iter().enumerate() {
        if position != 0 {
            phrase.push(' ');
        }
        let mut row = take(&mut value, BEGIN_BITS);
        phrase.push_str(text(data::BEGIN[row]));
        for _ in 2..length {
            let token = data::MIDDLE[row][take(&mut value, MIDDLE_BITS)];
            phrase.push_str(text(token));
            row = middle_row(token);
        }
        phrase.push_str(text(data::END32[row][take(&mut value, END_BITS)]));
    }
    debug_assert_eq!(value, 0);
    phrase
}

/// The one token in `row` that `remaining` starts with (rows are prefix-free), and its index.
fn parse(remaining: &mut &str, row: &[u16]) -> Option<(u64, u16)> {
    let (digit, &token) = row
        .iter()
        .enumerate()
        .find(|(_, token)| remaining.starts_with(text(**token)))?;
    *remaining = &remaining[text(token).len()..];
    Some((digit as u64, token))
}

/// Decode only canonical phrases: 3 or 4 words separated by single spaces, lowercase, nothing else.
pub fn decode_u64(phrase: &str) -> Option<u64> {
    validate();
    let words: Vec<&str> = phrase.split(' ').collect();
    if !(3..=4).contains(&words.len()) {
        return None;
    }
    let mut lengths = [0u8; 4];
    let mut value = 0u64;
    let mut offset = LAYOUT_BITS;
    // A phrase with more than 10 tokens would need more than 64 bits: reject it before shifting past them.
    let mut push = |digit: u64, width: u32| {
        if offset + width > 64 {
            return None;
        }
        value |= digit << offset;
        offset += width;
        Some(())
    };
    for (position, word) in words.iter().enumerate() {
        let mut remaining = *word;
        let (digit, _) = parse(&mut remaining, &data::BEGIN)?;
        push(digit, BEGIN_BITS)?;
        let mut row = digit as usize;
        let mut middles = 0;
        // Middles and endings are prefix-free together, so at most one of them matches here.
        loop {
            if let Some((digit, _)) = parse(&mut remaining, &data::END32[row]) {
                push(digit, END_BITS)?;
                break;
            }
            if middles == MAX_MIDDLES {
                return None;
            }
            let (digit, token) = parse(&mut remaining, &data::MIDDLE[row])?;
            push(digit, MIDDLE_BITS)?;
            row = middle_row(token);
            middles += 1;
        }
        if !remaining.is_empty() {
            return None;
        }
        lengths[position] = middles as u8 + 2;
    }
    let layout = LAYOUTS.iter().position(|layout| *layout == lengths)?;
    debug_assert_eq!(offset, 64);
    Some(value | layout as u64)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn layouts_are_every_split_of_ten_tokens() {
        let mut expected = Vec::new();
        for words in 1..=4u32 {
            for code in 0..3u32.pow(words) {
                let lengths: Vec<u8> = (0..words)
                    .map(|index| (code / 3u32.pow(index) % 3) as u8 + 2)
                    .rev()
                    .collect();
                if lengths.iter().map(|&length| u32::from(length)).sum::<u32>() == 10 {
                    let mut layout = [0u8; 4];
                    layout[..lengths.len()].copy_from_slice(&lengths);
                    expected.push(layout);
                }
            }
        }
        expected.sort();
        assert_eq!(expected, LAYOUTS);
        for layout in &LAYOUTS {
            let bits: u32 = LAYOUT_BITS
                + layout[..word_count(layout)]
                    .iter()
                    .map(|&length| BEGIN_BITS + MIDDLE_BITS * (u32::from(length) - 2) + END_BITS)
                    .sum::<u32>();
            assert_eq!(bits, 64, "{layout:?}");
        }
    }

    #[test]
    fn golden_and_canonical() {
        // Generated by models/compile_phrase.py's reference encoder.
        for (value, expected) in [
            (0x0, "maan maan maan mataizin"),
            (0x1, "maan maan matara matara"),
            (0x2, "maan maan mataizin maan"),
            (0xf, "mataizin mataizin maan"),
            (0x10, "kaan maan maan mataizin"),
            (0x2a, "partas matara mataizin"),
            (0x3e8, "gustes maan matara maan"),
            (0x75bcd15, "heim erkerege maan maan"),
            (0x7fffffffffffffff, "iteahuika iteahuika itura"),
            (0x8000000000000000, "maan maan maan mataizau"),
            (0xfffffffffffffffe, "iteahuika iteang iteang"),
            (0xffffffffffffffff, "iteahuika iteahuika itde"),
            (0x243f6a8885a308d3, "mung kiroot niun yeekwa"),
            (0xdeadbeefcafebabe, "vajaerna ilmiut garuzi"),
        ] {
            assert_eq!(encode_u64(value), expected, "{value:#x}");
            assert_eq!(decode_u64(expected), Some(value), "{expected}");
        }
        let phrase = encode_u64(123456789);
        for invalid in [
            format!(" {phrase}"),
            format!("{phrase} "),
            phrase.replace(' ', "  "),
            phrase.replace(' ', "\t"),
            phrase.to_uppercase(),
            format!("{phrase}x"),
            format!("{phrase} extra"),
            format!("{phrase} {phrase}"),
            phrase.replacen(' ', "", 1),
            // 4 words of 4 tokens: 16 tokens, more than 64 bits.
            ["mataizin"; 4].join(" "),
            "é".to_owned(),
            String::new(),
        ] {
            assert_eq!(decode_u64(&invalid), None, "{invalid:?}");
        }
        for end in 0..phrase.len() {
            assert_eq!(decode_u64(&phrase[..end]), None);
        }
    }

    #[test]
    fn distinct_roundtrips_reach_every_layout() {
        let mut state = 0x243f6a8885a308d3u64;
        let mut phrases = HashSet::new();
        let mut layouts = HashSet::new();
        for _ in 0..100_000 {
            state = state
                .wrapping_mul(6364136223846793005)
                .wrapping_add(1442695040888963407);
            let phrase = encode_u64(state);
            assert_eq!(decode_u64(&phrase), Some(state), "{phrase}");
            assert!(phrases.insert(phrase.clone()));
            let lengths: Vec<usize> = phrase.split(' ').map(str::len).collect();
            assert!(lengths.iter().all(|&letters| letters >= 4), "{phrase}");
            assert!(phrase.split(' ').all(has_vowel), "{phrase}");
            assert!(
                phrase.split(' ').all(|word| triple_free("", word)),
                "{phrase}"
            );
            layouts.insert(state & 15);
        }
        assert_eq!(layouts.len(), 16);
    }

    #[test]
    fn every_bit_of_every_layout_roundtrips() {
        for layout in 0..16u64 {
            for bit in LAYOUT_BITS..64 {
                for base in [0, !15] {
                    let value = (base ^ (1 << bit)) | layout;
                    let phrase = encode_u64(value);
                    assert_eq!(decode_u64(&phrase), Some(value), "{phrase}");
                }
            }
        }
    }
}
